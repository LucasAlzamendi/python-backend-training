# suma y resta (+ y -)
suma = 8 + 9
resta = 8 - 9 

print(f'Suma: {suma}')
print(f'Resta: {resta}')

# multi y div (* y /)
multi = 8 * 9
divi = 8 / 9 # Devuelve un float

print(f'Multi: {multi}')
print(f'Divi: {divi}')

# potenciacion (exponente) (**)

exponente = 8 ** 9

print(f'Exponente: {exponente}')

# división baja (//)

division_baja = 8 // 9 # Devuelve un entero redondeado hacia abajo

print(f'Division_Baja: {division_baja}')

# resto o módulo (%)

resto = 8 % 9

print(f'Resto: {resto}')